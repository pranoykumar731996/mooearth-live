export const ALL_WORLD_PLACES: WorldPlace[] = [
  ...ICONIC_LANDMARKS,
  ...FAMOUS_METROPOLISES,
  ...WORLD_CAPITALS,
];

/**
 * Finds the nearest specific place, city, or landmark to any coordinate on Earth.
 * Guarantees a specific place name is returned.
 */
export function findNearestWorldPlace(coord: GeoCoordinate): { place: WorldPlace; distanceKm: number } {
  let closest = ALL_WORLD_PLACES[0];
  let minDistance = Infinity;

  for (const place of ALL_WORLD_PLACES) {
    const dist = haversineDistance(coord, place.coordinates);
    if (dist < minDistance) {
      minDistance = dist;
      closest = place;
    }
  }

  return { place: closest, distanceKm: Math.round(minDistance) };
}

/**
 * Retrieves a curated, diverse set of mystery places for the Auto-Spot mode.
 */
export function getCuratedMysteryPlaces(): WorldPlace[] {
  // Focus on world wonders, famous metropolises, and prominent capitals
  return [
    ...ICONIC_LANDMARKS,
    ...FAMOUS_METROPOLISES,
    ...WORLD_CAPITALS.slice(0, 50), // Major capitals
  ];
}
